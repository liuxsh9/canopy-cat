export function paintCatShadow(ctx, x, y, radiusX = 5.2, radiusY = 1.25, alpha = 0.18) {
  if (alpha <= 0.01) return;
  const px = 1 / TREE_ART_SCALE;
  const cx = snapPx(x);
  const cy = snapPx(y);
  ctx.save();
  ctx.globalAlpha = clamp(alpha, 0, 1);
  ctx.fillStyle = 'rgb(42 36 48)';
  const rows = Math.max(1, Math.round(radiusY / px));
  for (let r = -rows; r <= rows; r += 1) {
    const ny = r / (rows + 0.5);
    const halfW = snapPx(radiusX * Math.sqrt(Math.max(0, 1 - ny * ny)));
    if (halfW > 0) ctx.fillRect(cx - halfW, cy + r * px, halfW * 2, px);
  }
  ctx.restore();
}
