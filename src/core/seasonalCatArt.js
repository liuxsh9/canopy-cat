const snapPx = value => Math.round(value * TREE_ART_SCALE) / TREE_ART_SCALE;

function rowsForBreed(breed, name) {
  const rawRows = RAW_FRAMES[name];
  if (!breed.curledEars) return rawRows;
  return rawRows.map((line, idx) => (
    line.includes('M.....M') && rawRows[idx + 1]?.includes('MmM...MmM')
      ? line.replace('M.....M', '.M...M.')
      : line.includes('M....M') && rawRows[idx + 1]?.includes('MmM..MmM')
        ? line.replace('M....M', '.M..M.')
        : line
  ));
}

export function createCatAtlas(document, breed) {
  const canvas = document.createElement('canvas');
  canvas.width = CAT_FRAME_WIDTH;
  canvas.height = CAT_FRAME_HEIGHT * CAT_FRAME_NAMES.length;
  const ctx = canvas.getContext('2d');
  if (!ctx) return canvas;
  ctx.imageSmoothingEnabled = false;
  CAT_FRAME_NAMES.forEach((name, frameIndex) => {
    const rows = rowsForBreed(breed, name);
    const baseY = frameIndex * CAT_FRAME_HEIGHT;
    rows.forEach((line, y) => {
      for (let x = 0; x < line.length; x += 1) {
        const ch = line[x];
        if (ch === '.') continue;
        const color = breed.palette[ch];
        if (!color) continue;
        ctx.fillStyle = color;
        ctx.fillRect(x, baseY + y, 1, 1);
      }
    });
  });
  return canvas;
}

export function paintCatTail(ctx, breed, rootX, rootY, ctrlX, ctrlY, tipX, tipY, options = {}) {
  const { facing = 1, thick = 1 } = options;
  const palette = breed.palette;
  const steps = 18;
  const px = 1 / TREE_ART_SCALE;
  const points = [];
  for (let i = 0; i <= steps; i += 1) {
    const t = i / steps;
    const inv = 1 - t;
    const lx = 2 * inv * t * ctrlX + t * t * tipX;
    const ly = 2 * inv * t * ctrlY + t * t * tipY;
    const sx = snapPx(rootX + lx * facing * px);
    const sy = snapPx(rootY + ly * px);
    if (!points.length || points[points.length - 1][0] !== sx || points[points.length - 1][1] !== sy) {
      points.push([sx, sy, t]);
    }
  }
  const tShadow = breed.tailPalette ? breed.tailPalette[0] : palette['2'];
  const tCore = breed.tailPalette ? breed.tailPalette[1] : palette['3'];
  const tHi = breed.tailPalette ? breed.tailPalette[2] : palette['4'];
  const fluffy = Boolean(breed.fluffyTail);
  ctx.fillStyle = tShadow;
  for (const [x, y, t] of points) {
    const full = thick >= 0.85 && (fluffy ? t < 0.92 : t < 0.82);
    ctx.fillRect(x - px, y, px * 3, px);
    ctx.fillRect(x, y - px, px, px * 3);
    if (full) ctx.fillRect(x - px, y + px, px * 3, px);
    if (fluffy && thick >= 0.8 && t < 0.88) {
      ctx.fillRect(x - px, y - px, px * 3, px);
      ctx.fillRect(x, y + px * 2, px, px);
    }
  }
  points.forEach(([x, y, t], idx) => {
    const isTip = breed.whiteTip && t >= 0.80;
    const isBand = breed.tailStripe && Math.floor(idx / 2) % 2 === 1 && !isTip;
    const core = isTip ? palette['6'] : isBand ? (breed.label.en === 'Calico' ? palette.b : palette.s) : tCore;
    const hi = isTip ? palette['6'] : isBand ? palette.a : tHi;
    ctx.fillStyle = core;
    ctx.fillRect(x, y, px * (t < 0.88 ? 2 : 1), px);
    if (fluffy && t < 0.82) ctx.fillRect(x, y + px, px, px);
    if (thick >= 0.7 && t < 0.86) {
      ctx.fillStyle = hi;
      ctx.fillRect(x, y - px, px, px);
    }
  });
}

export function paintCatFrame(ctx, atlas, frameName, x, y, facing = 1, angle = 0) {
  const index = CAT_FRAME_INDEX[frameName] ?? 0;
  const [pivotX, pivotY] = CAT_FRAME_PIVOTS[frameName] ?? CAT_FRAME_PIVOTS.default;
  const w = CAT_FRAME_WIDTH / TREE_ART_SCALE;
  const h = CAT_FRAME_HEIGHT / TREE_ART_SCALE;
  const ox = pivotX / TREE_ART_SCALE;
  const oy = pivotY / TREE_ART_SCALE;
  ctx.save();
  ctx.translate(snapPx(x), snapPx(y));
  if (angle) ctx.rotate(angle);
  if (facing < 0) ctx.scale(-1, 1);
  ctx.drawImage(atlas, 0, index * CAT_FRAME_HEIGHT, CAT_FRAME_WIDTH, CAT_FRAME_HEIGHT, -ox, -oy, w, h);
  ctx.restore();
}

export function paintCatPreview(canvas, breedKey) {
  const ctx = canvas?.getContext?.('2d');
  if (!ctx) return;
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  const breed = CAT_BREEDS[breedKey];
  if (!breed) return;
  const atlas = createCatAtlas(canvas.ownerDocument, breed);
  ctx.save();
  ctx.imageSmoothingEnabled = false;
  ctx.scale(2, 2);
  paintCatTail(ctx, breed, 14.25, 21.5, -5.0, 1.4, -8.8, -2.2, { facing: 1, thick: 1 });
  paintCatFrame(ctx, atlas, 'sit', 17.5, 23, 1, 0);
  ctx.restore();
}

const HEART_PIXELS = ['.1.1.', '12121', '12221', '.121.', '..1..'];
const Z_SMALL = ['111', '..1', '.1.', '111'];
const ALERT_PIXELS = ['11', '11', '11', '..', '11'];

export function paintPixelHeart(ctx, x, y, alpha) {
  if (alpha <= 0.02) return;
  const px = 1 / TREE_ART_SCALE;
  const sx = snapPx(x);
  const sy = snapPx(y);
  ctx.save();
  ctx.globalAlpha = clamp(alpha, 0, 1);
  HEART_PIXELS.forEach((row, ry) => {
    for (let rx = 0; rx < row.length; rx += 1) {
      const ch = row[rx];
      if (ch === '.') continue;
      ctx.fillStyle = ch === '1' ? 'rgb(206 86 112)' : 'rgb(246 154 172)';
      ctx.fillRect(sx + (rx - 2) * px, sy + (ry - 2) * px, px, px);
    }
  });
  ctx.restore();
}

